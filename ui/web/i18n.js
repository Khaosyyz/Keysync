export const LANGUAGES = { en: "English", zh: "中文" };
const LOCALES = { en: "en-US", zh: "zh-CN" };

let lang = "en";

export function setLanguage(code) {
  lang = code;
  document.documentElement.lang = LOCALES[code];
}

export const locale = () => LOCALES[lang];

export function t(key, vars = {}) {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, name) => vars[name]);
}

export function tNodes(key, vars) {
  return STRINGS[lang][key].split(/\{(\w+)\}/).map((part, i) => (i % 2 ? vars[part] : part));
}

export function translateStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
}

export function keyLabel(code) {
  const side = /(Left|Right)$/.exec(code);
  const base = (side ? code.slice(0, -side[1].length) : code).replace("Control", "Ctrl")
    .replace(/([a-z])([A-Z])/g, "$1 $2");
  return side ? `${t(`key.${side[1]}`)} ${base}` : base;
}

export function formatDuration(s) {
  if (s < 60) return t("dur.sec", { s: Math.max(s, 0.1).toFixed(1) });
  const total = Math.round(s);
  return t("dur.min", { m: Math.floor(total / 60), s: String(total % 60).padStart(2, "0") });
}
